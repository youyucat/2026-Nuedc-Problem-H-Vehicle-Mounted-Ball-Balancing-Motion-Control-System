/**
  * @brief 外部中断回调：Z 相零位
  */
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
  if (GPIO_Pin == Z_Pin)
  {
    encoder_z_isr();
  }
}

/**
  * @brief 定时器更新回调：TIM1 每个 STEP 脉冲调用一次
  */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
  if (htim->Instance == TIM1)
  {
    stepper_pulse_isr();
  }
}

/**
  * @brief USART1 接收中断：视觉模块 / 车主控数据帧入口
  *        单字节中断接收，字节先进环形缓冲，主循环里统一解析
  */
void USART1_IRQHandler(void)
{
  HAL_UART_IRQHandler(&huart1);
}

/**
  * @brief 接收完成回调：取走这一个字节，再挂起下一次接收
  */
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
  if (huart->Instance == USART1)
  {
    ball_ctrl_uart_rx_isr(ball_ctrl_uart_rx_byte());
    ball_ctrl_uart_start_rx();
  }
}

/**
  * @brief 串口错误回调（溢出/帧错误等）：重新挂起接收，防止串口从此哑掉
  */
void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart)
{
  if (huart->Instance == USART1)
  {
    ball_ctrl_uart_start_rx();
  }
}

